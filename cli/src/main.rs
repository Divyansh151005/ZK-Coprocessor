//! `create-zk-coprocessor` CLI (Phase 6).

use clap::{Parser, Subcommand};
use std::fs;
use std::path::PathBuf;

#[derive(Parser, Debug)]
#[command(name = "create-zk-coprocessor", about = "Scaffold a ZK coprocessor app")]
struct Cli {
    #[command(subcommand)]
    cmd: Commands,
}

#[derive(Subcommand, Debug)]
enum Commands {
    /// Create a new project scaffold
    New {
        name: String,
        #[arg(long, default_value = "compute")]
        template: String,
        #[arg(long)]
        path: Option<PathBuf>,
    },
    /// Dry-run deploy address book emission
    Deploy {
        #[arg(long, default_value = "anvil")]
        network: String,
    },
}

fn main() {
    let cli = Cli::parse();
    match cli.cmd {
        Commands::New {
            name,
            template,
            path,
        } => {
            let root = path.unwrap_or_else(|| PathBuf::from(&name));
            scaffold(&root, &name, &template).expect("scaffold failed");
            println!("created {} (template={template})", root.display());
            println!("folders: app/ (Rust guest) contracts/ (Solidity consumer)");
        }
        Commands::Deploy { network } => {
            let book = serde_json::json!({
                "network": network,
                "ProgramRegistry": "0x0000000000000000000000000000000000000001",
                "RequestRouter": "0x0000000000000000000000000000000000000002",
                "Fulfillment": "0x0000000000000000000000000000000000000003",
                "SP1VerifierGateway": "USE_VENDOR_DEPLOYMENT",
                "note": "dry-run address book — replace after forge script"
            });
            println!("{book}");
        }
    }
}

fn scaffold(root: &PathBuf, name: &str, template: &str) -> std::io::Result<()> {
    fs::create_dir_all(root.join("app/src"))?;
    fs::create_dir_all(root.join("contracts/src"))?;
    let guest = match template {
        "state" | "state-reading" => {
            r#"//! State-reading guest template (uses zk-coprocessor-sdk env::read_state).
#![no_main]
// sp1_zkvm::entrypoint!(main);
// use zk_coprocessor_sdk::env;
pub fn main() {
    // read witnesses, verify MPT, commit journal
}
"#
        }
        _ => {
            r#"//! Compute-only guest template.
#![no_main]
// sp1_zkvm::entrypoint!(main);
pub fn main() {
    // let a = sp1_zkvm::io::read::<u64>();
    // let b = sp1_zkvm::io::read::<u64>();
    // sp1_zkvm::io::commit(&(a.wrapping_add(b)));
}
"#
        }
    };
    fs::write(root.join("app/src/main.rs"), guest)?;
    fs::write(
        root.join("contracts/src/Consumer.sol"),
        r#"// SPDX-License-Identifier: MIT
pragma solidity ^0.8.20;

interface ICoprocessorConsumer {
    function receiveCoprocessorResult(bytes calldata journal) external;
}

contract Consumer is ICoprocessorConsumer {
    bytes public lastJournal;
    function receiveCoprocessorResult(bytes calldata journal) external override {
        lastJournal = journal;
    }
}
"#,
    )?;
    fs::write(
        root.join("README.md"),
        format!(
            "# {name}\n\nGenerated by `create-zk-coprocessor`.\n\nTemplate: {template}\n\n1. Implement guest in `app/`\n2. Implement callback in `contracts/`\n3. Register program + request via ZK-Coprocessor gateway\n"
        ),
    )?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::env::temp_dir;

    #[test]
    fn scaffolds_compute() {
        let dir = temp_dir().join(format!("zkc-scaffold-{}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        scaffold(&dir, "demo", "compute").unwrap();
        assert!(dir.join("app/src/main.rs").exists());
        assert!(dir.join("contracts/src/Consumer.sol").exists());
        let _ = fs::remove_dir_all(&dir);
    }
}
